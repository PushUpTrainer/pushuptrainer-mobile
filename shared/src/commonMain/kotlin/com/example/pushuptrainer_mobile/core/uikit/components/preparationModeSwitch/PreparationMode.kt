package com.example.pushuptrainer_mobile.core.uikit.components.preparationModeSwitch

/** Режим тренировки, выбранный переключателем на экране подготовки. */
enum class PreparationMode {

    /** «С целью»: пользователь задаёт число повторений. */
    WithGoal,

    /** «Без цели»: повторения считаются без лимита. */
    WithoutGoal,
}
